func generateRepoFindAll(g *protogen.GeneratedFile, entityName, tableName string) {
	g.P("// FindAll retrieves all ", entityName, "s with pagination")
	g.P("func (r *", entityName, "Repository) FindAll(ctx context.Context, offset, limit int) ([]*", entityName, ", error) {")
	g.P("	query := `SELECT /* columns */ FROM ", tableName, "s ORDER BY id LIMIT $1 OFFSET $2`")
	g.P("	rows, err := r.db.QueryContext(ctx, query, limit, offset)")
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	defer rows.Close()")
	g.P()
	g.P("	var entities []*", entityName)
	g.P("	for rows.Next() {")
	g.P("		entity := &", entityName, "{}")
	g.P("		if err := rows.Scan(/* &entity fields */); err != nil {")
	g.P("			return nil, err")
	g.P("		}")
	g.P("		entities = append(entities, entity)")
	g.P("	}")
	g.P()
	g.P("	return entities, rows.Err()")
	g.P("}")
	g.P()
}

func generateRepoCount(g *protogen.GeneratedFile, entityName, tableName string) {
	g.P("// Count returns the total number of ", entityName, "s")
	g.P("func (r *", entityName, "Repository) Count(ctx context.Context) (int64, error) {")
	g.P("	query := `SELECT COUNT(*) FROM ", tableName, "s`")
	g.P("	var count int64")
	g.P("	err := r.db.QueryRowContext(ctx, query).Scan(&count)")
	g.P("	return count, err")
	g.P("}")
	g.P()
}

func toSnakeCase(s string) string {
	var result strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteRune('_')
		}
		result.WriteRune(r)
	}
	return strings.ToLower(result.String())
}
