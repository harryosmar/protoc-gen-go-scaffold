// GenerateRepositories generates repository layer with database operations
func GenerateRepositories(gen *protogen.Plugin, file *protogen.File) {
	filename := file.GeneratedFilenamePrefix + "_repository.scaffold.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-go-scaffold. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("import (")
	g.P(`	"context"`)
	g.P(`	"database/sql"`)
	g.P(")")
	g.P()

	for _, message := range file.Messages {
		if isEntity(message) {
			generateRepositoryForEntity(g, message)
		}
	}
}

func generateRepositoryForEntity(g *protogen.GeneratedFile, message *protogen.Message) {
	entityName := message.GoIdent.GoName
	repoName := entityName + "Repository"
	tableName := toSnakeCase(entityName)

	g.P("// ", repoName, " handles database operations for ", entityName)
	g.P("type ", repoName, " struct {")
	g.P("	db *sql.DB")
	g.P("}")
	g.P()

	g.P("// New", repoName, " creates a new ", repoName)
	g.P("func New", repoName, "(db *sql.DB) *", repoName, " {")
	g.P("	return &", repoName, "{db: db}")
	g.P("}")
	g.P()

	// Generate CRUD methods
	generateRepoCreate(g, entityName, tableName)
	generateRepoFindByID(g, entityName, tableName)
	generateRepoUpdate(g, entityName, tableName)
	generateRepoDelete(g, entityName, tableName)
	generateRepoFindAll(g, entityName, tableName)
	generateRepoCount(g, entityName, tableName)
}

