func generateListHandler(g *protogen.GeneratedFile, entityName string) {
	g.P("// List", entityName, "s handles GET /", strings.ToLower(entityName), "s")
	g.P("func (h *", entityName, "Handler) List", entityName, "s(w http.ResponseWriter, r *http.Request) {")
	g.P("	page, _ := strconv.Atoi(r.URL.Query().Get(\"page\"))")
	g.P("	pageSize, _ := strconv.Atoi(r.URL.Query().Get(\"page_size\"))")
	g.P("	if page < 1 {")
	g.P("		page = 1")
	g.P("	}")
	g.P("	if pageSize < 1 || pageSize > 100 {")
	g.P("		pageSize = 10")
	g.P("	}")
	g.P()
	g.P("	entities, total, err := h.service.List(r.Context(), page, pageSize)")
	g.P("	if err != nil {")
	g.P("		http.Error(w, err.Error(), http.StatusInternalServerError)")
	g.P("		return")
	g.P("	}")
	g.P()
	g.P("	response := map[string]interface{}{")
	g.P("		\"data\":       entities,")
	g.P("		\"page\":       page,")
	g.P("		\"page_size\":  pageSize,")
	g.P("		\"total\":      total,")
	g.P("	}")
	g.P()
	g.P("	w.Header().Set(\"Content-Type\", \"application/json\")")
	g.P("	json.NewEncoder(w).Encode(response)")
	g.P("}")
	g.P()
}

func isEntity(message *protogen.Message) bool {
	// Check if message has entity annotation
	// For now, we'll consider messages with "Entity" suffix as entities
	return strings.HasSuffix(message.GoIdent.GoName, "Entity") || 
		   hasEntityOption(message)
}

func hasEntityOption(message *protogen.Message) bool {
	// TODO: Check for custom proto options like (scaffold.entity) = true
	// This requires defining custom proto options
	return false
}
