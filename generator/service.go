func generateServiceList(g *protogen.GeneratedFile, entityName string) {
	g.P("// List retrieves a paginated list of ", entityName, "s")
	g.P("func (s *", entityName, "Service) List(ctx context.Context, page, pageSize int) ([]*", entityName, ", int64, error) {")
	g.P("	offset := (page - 1) * pageSize")
	g.P("	entities, err := s.repo.FindAll(ctx, offset, pageSize)")
	g.P("	if err != nil {")
	g.P("		return nil, 0, err")
	g.P("	}")
	g.P()
	g.P("	total, err := s.repo.Count(ctx)")
	g.P("	if err != nil {")
	g.P("		return nil, 0, err")
	g.P("	}")
	g.P()
	g.P("	return entities, total, nil")
	g.P("}")
	g.P()
}
