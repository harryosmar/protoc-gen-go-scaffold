func generateServiceGetByID(g *protogen.GeneratedFile, entityName string) {
	g.P("// GetByID retrieves a ", entityName, " by ID")
	g.P("func (s *", entityName, "Service) GetByID(ctx context.Context, id int64) (*", entityName, ", error) {")
	g.P("	entity, err := s.repo.FindByID(ctx, id)")
	g.P("	if err != nil {")
	g.P("		return nil, err")
	g.P("	}")
	g.P("	if entity == nil {")
	g.P("		return nil, errors.New(\"", strings.ToLower(entityName), " not found\")")
	g.P("	}")
	g.P("	return entity, nil")
	g.P("}")
	g.P()
}

