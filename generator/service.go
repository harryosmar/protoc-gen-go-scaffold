package generator

import (
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// GenerateServices generates service layer with business logic
func GenerateServices(gen *protogen.Plugin, file *protogen.File) {
	filename := file.GeneratedFilenamePrefix + "_service.scaffold.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-go-scaffold. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()
	g.P("import (")
	g.P(`	"context"`)
	g.P(`	"errors"`)
	g.P(")")
	g.P()

	for _, message := range file.Messages {
		if isEntity(message) {
			generateServiceForEntity(g, message)
		}
	}
}

func generateServiceForEntity(g *protogen.GeneratedFile, message *protogen.Message) {
	entityName := message.GoIdent.GoName
	serviceName := entityName + "Service"

	g.P("// ", serviceName, " provides business logic for ", entityName)
	g.P("type ", serviceName, " struct {")
	g.P("	repo *", entityName, "Repository")
	g.P("}")
	g.P()

	g.P("// New", serviceName, " creates a new ", serviceName)
	g.P("func New", serviceName, "(repo *", entityName, "Repository) *", serviceName, " {")
	g.P("	return &", serviceName, "{repo: repo}")
	g.P("}")
	g.P()

	// Generate CRUD methods
	generateServiceCreate(g, entityName)
	generateServiceGetByID(g, entityName)
	generateServiceUpdate(g, entityName)
	generateServiceDelete(g, entityName)
	generateServiceList(g, entityName)
}

